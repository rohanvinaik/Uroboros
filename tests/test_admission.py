def _settled(path: str, unproven: int = 3, crash: int = 2) -> dict:
    """A settled converge's typed state, as possession writes it (measured from a real draw, 2026-10-07)."""
    return {
        "verb": "converge",
        "code": "settled",
        "standing": {"code": "complete", "cut_reasons": [], "killed": [38, 41], "modulo_unproven": unproven, "modulo_crash_only": crash, "verification": None},
        "facts": {"wrote": {"tests": 4, "path": path}, "unproven_equivalent": unproven, "crash_only": crash, "residual": "probed"},
    }


def _played(states: dict, classes: dict | None = None, outcome: str = "written", setup: str = "clean") -> dict:
    functions = {
        q: {
            "runs": [{"state": {"verb": "audit"}, "taste": False}, {"state": s, "taste": False}, {"state": {"verb": "plan"}, "taste": True}],
            "ending": "converge:settled:probed",
            "class": (classes or {}).get(q, "clean"),
        }
        for q, s in states.items()
    }
    return {
        "outcome": outcome,
        "grant": {"contract_writer": "lead", "code_writer": "laguna-xs-2.1", "admission": "lead"},
        "detective": {"setup": {"runs": [], "ending": "regime:ok", "class": setup}, "functions": functions},
    }


def test_a_unit_is_clean_only_when_every_ending_is():
    """Admission's first check (separation [8]): the play wrote the module and every ending of its Detective phase, the
    folder's setup and each function's, is classed clean; otherwise the first that is not is named."""
    state = _settled("tests/detective/x.py")
    assert admission.clean(_played({"clamp": state})) == "clean"
    assert admission.clean(_played({"clamp": state}, outcome="incomplete")) == "not_written:incomplete"
    assert admission.clean(_played({"clamp": state}, setup="world_wrong")) == "world_wrong:"
    assert admission.clean(_played({"a": state, "b": state}, {"b": "handed_back"})) == "handed_back:b"
    assert admission.clean(_played({"a": state}, {"a": ""})) == "unread:a"
    for junk in (None, {}, {"outcome": "written"}, {"outcome": "written", "detective": {"setup": {}}}):
        assert admission.clean(junk) == "unread", junk


def test_the_survivors_are_recorded_by_detectives_own_class():
    """What a function's last correctness run left, by Detective's own class, from its typed state; nothing flagged and
    nothing probed further (separation [8] and [11]). The style passes after it are not its standing."""
    played = _played({"clamp": _settled("tests/detective/test_clamp_synth.py"), "bare": {"verb": "converge"}})
    played["detective"]["functions"]["none"] = {"runs": [], "class": "clean"}
    assert admission.survivors(played) == {
        "clamp": {"standing": "complete", "killed": [38, 41], "residual": "probed", "unproven_equivalent": 3, "crash_only": 2},
        "bare": {"standing": "unread", "killed": None, "residual": None},
        "none": {"standing": "unread"},
    }
    assert admission.pinned_file(played, "clamp") == "tests/detective/test_clamp_synth.py"
    assert admission.pinned_file(played, "bare") == admission.pinned_file(played, "nowhere") == admission.pinned_file(None, "clamp") == ""
    assert admission.survivors(None) == admission.survivors({"detective": {"functions": []}}) == {}


def test_the_records_detective_pinned_are_read_by_their_form():
    """Detective's own test forms, read as typed records: a value pin, a raise pin with its message and one without, a
    golden table row by row; a test in any other form is named unread, never guessed."""
    assert admission.pins(PINS) == [
        {"test": "test_clamp_value_0", "call": "clamp(value=1, low=2, high=3)", "outcome": {"returns": "2"}},
        {"test": "test_clamp_value_1", "call": "clamp(value=5, low=10, high=0)", "outcome": {"raises": "ValueError", "message": "low bound must not exceed high bound"}},
        {"test": "test_clamp_value_2", "call": "clamp(value=5, low=10, high=0)", "outcome": {"raises": "ValueError", "message": None}},
        {"test": "test_clamp_golden[0]", "call": "clamp(0, 1, 2)", "outcome": {"returns": "1"}},
        {"test": "test_clamp_golden[1]", "call": "clamp(3, 1, 2)", "outcome": {"returns": "2"}},
        {"test": "test_clamp_property", "unread": "form"},
    ]
    assert admission.pins("def test_x(:\n") == [{"test": "", "unread": "syntax"}]
    assert admission.pins("def helper():\n    pass\n") == []
    odd = "import pytest\n\n@pytest.mark.parametrize('a, b', [(1, 2)])\ndef test_t(a, b):\n    assert a == b\n"
    assert admission.pins(odd) == [{"test": "test_t", "unread": "form"}]


def test_the_intent_check_answers_each_record_and_routes_what_it_cannot_pass():
    """One verdict per readable record, from the verdicts the function's contract allows: agrees, cannot tell, or a
    contradiction naming an intent test or coverage line. A contradiction is a hand-back to the lead, then Sol (the same
    question as a failing intent test); a cannot-tell, and a record Detective pinned in a form admission does not read,
    go to the founder (separation [8])."""
    form = admission.check_form(2, ["test_clamp", "test_clamp_refuses"], 1)
    verdicts = ["agrees", "cannot_tell", "contradicts:test_clamp", "contradicts:test_clamp_refuses", "contradicts:covers[0]"]
    assert form == {"type": "object", "properties": {"r0": {"enum": verdicts}, "r1": {"enum": verdicts}}, "required": ["r0", "r1"], "additionalProperties": False}
    assert admission.check_form(0, [], 0) == {"type": "object", "properties": {}, "required": [], "additionalProperties": False}
    assert admission.intent_names("def test_a():\n    pass\n\n\ndef helper():\n    pass\n\n\ndef test_b():\n    pass\n") == ["test_a", "test_b"]
    assert admission.intent_names("def (") == admission.intent_names(None) == []
    records = admission.pins(PINS)
    given = {"r0": "agrees", "r1": "contradicts:test_clamp", "r2": "agrees", "r3": "cannot_tell", "r4": "agrees"}
    backs = admission.held_back("clamp", records, given)
    every = list(decisions.RECEIVER_DECISIONS)
    assert backs == [
        {"function": "clamp", "ending": "admission:contradicts", "evidence": {"pin": records[1], "by": "test_clamp"}, "receivers": ["lead", "sol"], "decisions": every},
        {"function": "clamp", "ending": "admission:cannot_tell", "evidence": {"pin": records[3]}, "receivers": ["founder"], "decisions": every},
        {"function": "clamp", "ending": "admission:cannot_tell", "evidence": {"pin": records[5]}, "receivers": ["founder"], "decisions": every},
    ]
    assert admission.held_back("clamp", records[:1], {"r0": "agrees"}) == []
    assert admission.held_back("clamp", records[:1], {})[0]["ending"] == "admission:cannot_tell"  # an unanswered record is not passed
    assert decisions.handback_receivers("audit:fix_failing_test") == ["lead", "sol"] and decisions.handback_receivers("doctor:spiral") == ["admission"]


def _node() -> dict:
    return {
        "function": "clamp",
        "doc": {"prose": "A value held to a range.", "operations": [{"category": "BOUNDARY", "what": "the bounds"}]},
        "intent_test": {"source": "def test_clamp():\n    assert clamp(1, 2, 3) == 2\n", "covers": [{"category": "BOUNDARY", "subject": "s", "range": "r"}, "not a line"]},
    }


def test_the_intent_check_is_one_call_per_function():
    """``intent_check``: one call reads the function's docstring, its intent tests and coverage lines, and each readable
    record Detective pinned, by its number; its reply is held at decode time to one verdict per record. A function with
    nothing readable pinned makes no call."""
    records = admission.pins(PINS)
    chat = FakeChat(json.dumps({"verdicts": {f"r{i}": "agrees" for i in range(5)}}))
    code, verdicts, _out = admission.intent_check(_node(), "clamp", records, "qwen3-coder-next", chat=chat)
    assert (code, verdicts, chat.calls) == ("checked", {f"r{i}": "agrees" for i in range(5)}, 1)
    payload = chat.payloads[0]
    assert payload["format"]["properties"]["verdicts"] == admission.check_form(5, ["test_clamp"], 1)
    message = payload["messages"][0]["content"]
    assert '- r0: clamp(value=1, low=2, high=3) -> {"returns": "2"}' in message and "- r4: clamp(3, 1, 2)" in message
    assert "- covers[0]:" in message and "A value held to a range." in message and "test_clamp_property" not in message
    chat = FakeChat()
    assert admission.intent_check(_node(), "clamp", [{"test": "t", "unread": "form"}], "qwen3-coder-next", chat=chat)[:2] == ("nothing_to_check", {})
    assert admission.intent_check(_node(), "clamp", records, "nowhere", chat=chat)[:2] == ("unknown_model", {})
    assert chat.calls == 0
    failed = admission.intent_check(_node(), "clamp", records, "qwen3-coder-next", chat=FakeChat("not json", "not json"))
    assert failed[0].startswith("call_") and failed[1] == {}


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=False)


def _repo(tmp_path: Path, gate: int = 0) -> Path:
    repo = tmp_path / "target"
    (repo / "scripts").mkdir(parents=True)
    (repo / "scripts" / "ci_local.sh").write_text(f"exit {gate}\n")
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "-c", "user.email=t@t", "-c", "user.name=t", "add", ".")
    _git(repo, "-c", "user.email=t@t", "-c", "user.name=t", "commit", "-q", "-m", "start")
    _git(repo, "config", "user.email", "t@t")
    _git(repo, "config", "user.name", "t")
    return repo


def _unit(tmp_path: Path) -> Path:
    unit = tmp_path / "unit"
    (unit / "tests" / "detective").mkdir(parents=True)
    (unit / "clamp.py").write_text("def clamp(value, low, high):\n    return max(low, min(value, high))\n")
    (unit / "tests" / "test_clamp.py").write_text("def test_clamp():\n    pass\n")
    # the forms Detective writes, without the one admission does not read (that one goes to the founder)
    readable = PINS.split("\n\n@pytest.mark.detective\ndef test_clamp_property")[0] + "\n"
    (unit / "tests" / "detective" / "test_clamp_synth.py").write_text(readable)
    return unit


def test_placement_commits_the_module_and_both_test_sets_only_when_the_gate_passes(tmp_path):
    """Placement (separation [8]): the module at its contract path, its intent tests and Detective's pins, into the
    target; then the target's own gate; a commit on main with no trailers only if it passes, never a push. A gate that
    fails leaves the target as it was. A target that is no repository, holds uncommitted changes or is not on main is
    refused before anything is placed."""
    unit, source = _unit(tmp_path), {"path": "clamp.py"}
    pinned = ["tests/detective/test_clamp_synth.py"]
    files = admission.placed_files(unit, source, pinned)
    assert files == [[str(unit / "clamp.py"), "clamp.py"], [str(unit / "tests/test_clamp.py"), "tests/test_clamp.py"], [str(unit / pinned[0]), pinned[0]]]
    repo = _repo(tmp_path)
    code, commit = admission.place(unit, source, pinned, repo, "admit clamp.py")
    assert code == "placed" and commit == _git(repo, "rev-parse", "HEAD").stdout.strip()
    assert _git(repo, "log", "-1", "--format=%B").stdout.strip() == "admit clamp.py"
    assert sorted(_git(repo, "show", "--name-only", "--format=", "HEAD").stdout.split()) == sorted(to for _origin, to in files)
    assert _git(repo, "status", "--porcelain").stdout == "" and (repo / "clamp.py").read_text() == (unit / "clamp.py").read_text()
    failing = _repo(tmp_path / "second", gate=3)
    (failing / "clamp.py").write_text("# an older clamp\n")
    _git(failing, "add", "clamp.py")
    _git(failing, "commit", "-q", "-m", "older")
    assert admission.place(unit, source, pinned, failing, "admit clamp.py") == ("target:exists:clamp.py", "")
    assert _git(failing, "status", "--porcelain").stdout == "" and (failing / "clamp.py").read_text() == "# an older clamp\n"
    rejected = _repo(tmp_path / "failing_gate", gate=3)
    code, detail = admission.place(unit, source, pinned, rejected, "admit clamp.py")
    assert (code, detail["undo"]) == ("gate:3", "undone")
    assert _git(rejected, "status", "--porcelain").stdout == ""
    assert not (rejected / "tests").exists()
    assert (unit / "admission_gate.log").exists()
    (repo / "loose.txt").write_text("x")
    assert admission.place(unit, source, pinned, repo, "m") == ("target:dirty", "")
    assert admission.place(unit, source, pinned, tmp_path / "nowhere", "m") == ("target:not_a_repository", "")
    side = _repo(tmp_path / "third")
    _git(side, "checkout", "-q", "-b", "side")
    assert admission.place(unit, source, pinned, side, "m") == ("target:not_main", "")
    assert admission.place(unit, source, ["tests/detective/absent.py"], _repo(tmp_path / "fourth"), "m")[0].startswith("unit:missing:")


def _admissible(tmp_path: Path) -> Path:
    unit = _unit(tmp_path)
    pin = "tests/detective/test_clamp_synth.py"
    key = "clamp.py::clamp"
    played = _played({"clamp": _settled(pin)})
    played["detective"]["setup"]["route"] = "done"
    fn = played["detective"]["functions"]["clamp"]
    fn["route"] = "done"
    final = f"FINAL {key}: COMPLETE"
    fn["runs"] = [{"decision": {"final": final, "state": _settled(pin)}, "written_path": str(unit / pin), "function_digest": "digest"}]
    (unit / "play.json").write_text(json.dumps(played))
    source = json.loads((Path(__file__).parent / "fixtures/corpus/clamp/contract.json").read_text())
    node = ast.parse((unit / "clamp.py").read_text()).body[0]
    reply = {
        "signature": {"args": contract.json_from_ast(node.args)[1], "returns": None, "decorator_list": []},
        "code": [contract.json_from_ast(stmt)[1] for stmt in node.body],
    }
    status, source = contract.fill(source, "clamp", reply)
    assert status == "filled"
    (unit / "clamp.py").write_text(contract.render_module(source)[1])
    (unit / "tests/test_clamp.py").write_text(contract.render_tests(source)[1])
    labels = {key: {"standing": "complete", "function_digest": "digest", "refusal": "", "cut_reasons": []}}
    (unit / "tests/detective/certificates.json").write_text(json.dumps(labels))
    (unit / "contract.json").write_text(json.dumps(source))
    return unit


def test_admit_uses_terminal_detective_route_and_copies_its_pin(tmp_path, monkeypatch):
    unit = _admissible(tmp_path)
    chat = FakeChat()
    record = admission.admit(unit, chat=chat)
    assert (record["outcome"], record["bar"], record["survivors"]["clamp"]["unproven_equivalent"]) == ("checked", "pass", 3)
    assert chat.calls == 0

    def labels(target, _module, entries, _engine):
        (target / "tests/detective/certificates.json").write_text(json.dumps(entries))
        return "placed"

    monkeypatch.setattr(admission.detective, "place_certificates", labels)
    repo = _repo(tmp_path)
    record = admission.admit(unit, repo, chat=chat)
    assert record["outcome"] == "admitted"
    assert (repo / "tests/detective/test_clamp_synth.py").exists()
    assert (repo / "tests/detective/certificates.json").exists()
    assert _git(repo, "log", "-1", "--format=%B").stdout.splitlines()[:3] == [
        "admit clamp.py:",
        f"contract {record['contract_digest']}",
        "clamp.py::clamp: FINAL clamp.py::clamp: COMPLETE",
    ]
    play = unit / "play.json"
    record = json.loads(play.read_text())
    record["detective"]["functions"]["clamp"]["route"] = "handback"
    play.write_text(json.dumps(record))
    assert admission.admit(unit, chat=chat)["outcome"] == "unclean:not_done:clamp:converge:settled:probed"
    play.write_text("not json")
    assert admission.admit(unit, chat=chat)["outcome"] == "unreadable"


def test_commit_refusal_restores_files_index_and_folders(tmp_path):
    unit = _unit(tmp_path)
    repo = _repo(tmp_path)
    hook = repo / ".git/hooks/pre-commit"
    hook.write_text("#!/bin/sh\nexit 9\n")
    hook.chmod(0o755)
    before = _git(repo, "rev-parse", "HEAD").stdout
    code, detail = admission.place(unit, {"path": "clamp.py"}, ["tests/detective/test_clamp_synth.py"], repo, "admit")
    assert code.startswith("commit:")
    assert detail["undo"] == "undone"
